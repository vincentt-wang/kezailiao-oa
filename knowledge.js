/* ── 今日卡片 ── */
function todayCard(){
  const list = TODAY.catch.map(c=>{
    const dot = c.status==="充足" ? "🟢" : (c.status==="少量" ? "🟡" : "🔴");
    return `${dot} ${c.name}　${c.priceHint}`;
  }).join("\n");
  return `${TODAY.date}　${TODAY.weekday}\n\n今天有這些：\n${list}\n\n` +
    `拍賣 ${TODAY.auctionTime} 開始\n人潮預估：${TODAY.crowdLevel}\n${TODAY.crowdNote}\n\n` +
    `※ ${TODAY.notice}`;
}

/* ── 出口防線。這幾類話不能讓它說出口 ── */
const GUARDS = [
  { name:"不報價保證", re:/保證|一定最便宜|最低價|絕對/, fix:t=>t.replace(/保證|絕對/g,"") },
  { name:"不假裝是官方", re:/我們漁會|本會決定|官方公告/, fix:t=>t },
  { name:"不承諾庫存", re:/一定有|還有很多|買得到/, fix:t=>t }
];

function route(input){
  const q = (input||"").trim();
  if(!q) return { id:"empty", text:GREET };
  for(const r of ROUTES){
    if(r.re.test(q)){
      let t = r.fn();
      GUARDS.forEach(g=>{ if(g.re.test(t)) t = g.fix(t); });
      return { id:r.id, text:t };
    }
  }
  return { id:"fallback", text:FALLBACK };
}

